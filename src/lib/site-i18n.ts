export function isRtl(lang: string) {
  return lang === "ar";
}

export function getProductTypeName(category: string, lang: string) {
  const c = getSiteCopy(lang);
  if (category.includes("雾化")) return c.mist;
  if (category.includes("电子")) return c.electric;
  if (category.includes("酒精")) return c.ethanol;
  if (category.includes("投影") || category.includes("全息")) return c.holographic;
  return c.wholesaleFactory;
}
